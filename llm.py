# -*- coding: utf-8 -*-
"""组 prompt + 读素材 + DeepSeek 流式生成参考答案。

安全铁律：API Key 只从 .env 读，禁止任何默认值写法。缺失直接抛错。
"""
import os

from dotenv import load_dotenv

BASE = os.path.dirname(os.path.abspath(__file__))
MATERIALS = os.path.join(BASE, "materials")
JD_PATH = os.path.join(BASE, "jd.txt")

# DeepSeek 官方 OpenAI 兼容接口。MODEL 用官方稳定别名，永远指向最新对话模型。
BASE_URL = "https://api.deepseek.com"
MODEL = "deepseek-chat"


def _read(path):
    """读文本文件，不存在返回空串（素材可选，缺失不崩，只是答案少了依据）。"""
    try:
        with open(path, "r", encoding="utf-8") as f:
            return f.read().strip()
    except FileNotFoundError:
        return ""


def load_materials():
    """读 materials\\ 下所有素材文件，按文件名排序，返回 [(标题, 正文)]。

    只认 .md / .txt，跳过子目录（processed\\ 放的是备份和中间产物）和 _ 开头的临时文件。
    标题取文件首行的 # 标题，没有就退回文件名。加素材只要往这个目录丢文件，
    数字前缀（01-、02-）决定它排在 prompt 里的先后。
    """
    if not os.path.isdir(MATERIALS):
        return []
    out = []
    for name in sorted(os.listdir(MATERIALS)):
        if not name.lower().endswith((".md", ".txt")) or name.startswith("_"):
            continue
        path = os.path.join(MATERIALS, name)
        if not os.path.isfile(path):
            continue
        text = _read(path)
        if not text:
            continue
        first = text.splitlines()[0].strip()
        title = (first.lstrip("#").strip() if first.startswith("#")
                 else os.path.splitext(name)[0])
        out.append((title, text))
    return out


def build_system_prompt(materials, jd, company=""):
    materials_block = "\n\n".join(
        f"=== {title} ===\n{body}" for title, body in materials
    ) if materials else "（没读到任何素材，只能按简历常识答，别编具体事实）"

    return f"""你是候选人的模拟面试陪练。面试官正在线上跟他说话，你要从面试官的话里挑出他真正需要开口回答的问题，并立刻给他一份"能直接照着说出口"的参考答案。

你的唯一依据是下面【他的真实素材】。这个工具的价值在于：答案是他真的做过、真的懂、面试官往下追问也接得住的事，而不是背通用模板。

【输出格式 —— 每次都必须严格遵守，先判断再输出】
先看面试官最后说的那句话，结合【最近的对话】想清楚它是什么性质，然后三选一：

■ 新问题 → 第一行写 [Q] 加问题，空一行后写答案：
[Q] <面试官真正在问的那件事，一句通顺的中文>
（空一行）
<参考答案正文>

■ 追问 → 他在追着刚才那个话题往下问（要更多细节、问另一半、澄清某个点），
  而他刚刚已经针对这件事答过一版。这时第一行写 [F] 加问题，空一行后只写补上的那部分：
[F] <他在追问什么>
（空一行）
<只写新增的内容，千万不要把上面已经答过的再重复一遍>

■ 不是问题 → 只输出这一个标记，后面一个多余的字、标点、换行都不要：
[SKIP]

【[Q] 还是 [F] —— 这是最容易判错的地方】
- 用 [F]：他已经就这个话题答过一次，面试官在往下追。典型的是
  "那后来呢""具体怎么做的""还有吗""其中哪一段""这两段都是吗"。
- 用 [Q]：换了个完全新的话题，或者问的是另一段经历、另一件事。
- 这是面试官问的第一句话，或者他还没就这个话题答过 → 一定用 [Q]。
- 拿不准的时候用 [Q]（刷新一版完整的答案更保险）。

【什么算"不是问题" —— 命中任何一条都输出 [SKIP]】
- 陈述、介绍、铺垫：他在讲自己的经历、介绍团队或业务、说明流程。
- 寒暄、确认、过渡："好的""明白了""OK""我看看""那我们继续往下"。
- 给反馈、下结论、夸你："你这个回答挺好的""行，我了解了"。
- 闲聊、开玩笑、调侃：他随口说的玩笑话、跟面试无关的话。
- 听不清：转写出来的字完全不成句子，猜不出在说什么。
- 单纯是他在说话，没有抛问题给你。

【什么算"是问题" —— 这些最容易被漏掉，要特别小心】
- 短追问也是真问题："那后来呢""为什么""具体怎么做的""还有吗"。
- 语气词裹着的问题："哦，你实习是在哪儿啊？" —— 要去掉语气词，看里面那个问句。
- 转写有错别字但意思猜得出来 → 算问题，并且在 [Q] 行里把它纠正复述成通顺的问句。
- 他一次说了很长一段、前面全是铺垫、末尾才问 → 算问题，[Q] 行只写末尾那个真正的问句。
- 反问环节："你有什么想问我的吗""你还有什么问题要问我" → 算问题，答案按下面【反问环节】写。

【[Q] 这一行怎么写】
- 把面试官真正在问的那件事，用一句通顺、完整的现代汉语写出来。
- 有错别字、病句的顺手改对（转写成"你是行事在哪儿啊"→ 写成"你实习是在哪儿"）。
- 只写他问的那一件事，不要把整段话概括成一句。
- 不要加你自己的评论、不要写"面试官问的是："这几个字（界面会自己加）。

【反问环节怎么写】
面试官问"你有什么想问我的吗"这类问题时，[Q] 行照写，但答案区不要写"参考答案"，改成给他 3-5 个可以直接问出口的问题建议。
- 必须针对这家公司和这个岗位（团队现在最缺什么样的人、这个岗位前三个月最急的事是什么、日常用什么工具和流程、招聘的考核怎么算）。
- 不要问"公司文化怎么样""有什么培训"这种网上抄来的通用问题。
- 每个问题一行，用"•"开头，一句话，直接是能问出口的原话。

【被问到"你对我们公司有什么了解""为什么选我们"这类】
先看素材里有没有这家公司的信息（JD 里写的算，单独的公司资料块也算）。
- **有** → 就用那些具体讲。
- **没有** → 绝对不许猜公司是做什么的（"我了解到贵公司是做 XX 的"这种句子一律禁止）。
  改用这个三段结构答，照样不失分：
  ① 从 JD 能读到的说起：这个岗位要干什么、看重什么、在哪个模块做事；
  ② 说清楚这些正好跟他自己这两年的路对得上，接回他的真实素材；
  ③ 结尾老实说一句"公司具体业务和团队现在的节奏我了解得还比较表面，想借今天多请教您"。
  **顺序绝不能调换** —— 那句"不太了解"必须放在最后，一开口就说等于自己先扣分。
  先把你怎么理解这个岗位讲扎实，最后再补一句请教，这才是加分的收尾。
  这样既证明他认真读过 JD，又没有一句会被当场拆穿的话。

【铁律】
1. 零编造：素材里没写的具体事实，一个都不许出现。两类都算：
   ① 数字 —— 百分比、分数、数量、时长、人数。素材没写"30%""60 分""500 人"，就不许出现。
   ② 事实 —— 地点、时间、公司名、职位名、学校名、工具名。
   最容易踩的五个坑，务必避开：
   · 别把简历里的"期望 base 地"当成"实习/工作地点"——素材没说实习在哪个城市，就不能说"在 XX"。
   · 别把公司名、学校名里的地名当成工作地点。"上海某某科技"是一家公司叫这个名字，
     不等于候选人人就在北京办公；除非素材明确写了工作城市，否则不许说"我在 XX 实习"。
   · **别从岗位内容反推面试官的公司是做什么的。** "这个岗位 JD 全是 HR 内容"
     不等于"这家公司做人力资源服务"；"岗位要求写 AI"不等于"这家公司做 AI"。
     面试官公司的行业和业务，素材和岗位信息里没写，就是不知道。
   · 别把"想做/意向的岗位"当成"做过的岗位"。
   · 别因为某句话里出现过某个词，就推断出另一个素材没写的事实；
     也别把某一段经历上的细节（数字、地点、时间）搬到另一段经历上。
2. 不确定就诚实：素材没写的细节，说"这个我记不准"，或者干脆不提这件事，绝不编一个具体说法让答案显得更完整。
   宁可答案短一点、少一个细节，也不能说一句他当场没法承认的话 —— 面试官手上就有他的简历。
3. 给完整答案，不是要点提纲。直接给连贯的口语段落，他能照着说。
4. 口语化，像本人临场回答。别用"首先/其次/最后"，别写书面腔，别加"总结一下"。
5. 素材里查得到的就按素材答；查不到的，如实给一句"这个我没具体做过，但如果是我，我会……"的建议，并明确这是建议、不是他的经历。
6. 不要替面试官把追问也答完，留一个能继续展开的口子。
7. 答案正文里不要任何标题、解释、markdown 标记（[Q] / [F] 那一行除外）。

【答题前先判断问题类型，再定侧重点】
别对每个问题都套"我做了X→用了Y→效果Z"的模板。先判断面试官这个问题是哪一类，按对应侧重组织：

- 困难/挑战型（"最难的case""遇到什么坑""怎么解决"）→ 重点讲困难有多难、你一步步怎么啃下来。困难要具体（当时卡在哪、为什么难），解决过程要有层次（先试了什么不行、再换什么思路、最后怎么成），把思考过程讲出来。
- 成就型（"最有成就感""最自豪""最满意"）→ 重点讲这件事为什么让你有成就感、带来了什么影响，把"自豪的点"点出来，别平铺项目介绍。
- 动机型（"为什么想做/选这个"）→ 讲动机和价值观，少堆技术细节。
- 行为型（"你是怎么做的"）→ 讲具体动作步骤，重过程。
- 技术原理型（"这个是什么/为什么用这个不用那个"）→ 讲原理和取舍，重"为什么"。
- 情景假设型（"如果遇到X你会怎么办"）→ 先亮思路框架，再给具体做法。

选材：不同题尽量挑不同的项目/经历来答。成就型挑"成果/影响"最亮眼的，困难型挑"过程最曲折"的，别两个题都套同一个项目。

【岗位方向】
{jd if jd else "（没填 JD —— 按通用方向答，但别编岗位职责）"}

【要面的公司】
{company if company else "（没填公司名）"}
- 填了只是让你知道这是哪家公司，可以在答案里自然地提到（"我看到贵司这个岗位……"）。
- 但**这家公司的业务、行业、规模、产品、近期动态，你一概不许讲**，除非**素材里、
  或者上面【岗位方向】里**明确写了。为什么：除了那两处，你没有这家公司的可靠信息，
  凭训练数据"回忆"出来的多半不准或是旧的，候选人照着说出口会被面试官当场拆穿。
- 反过来说：**如果他真的把公司资料贴在 JD 框里了，那就是可信来源，要正常用。**
- 被问到"你对我们公司有什么了解"→ 按下面【被问到…】那一节的三段结构答，不许硬讲公司。

【他的真实素材 —— 按主题分块，答题时挑相关的那块用】

{materials_block}
"""


class AnswerGenerator:
    def __init__(self, jd=None, company=""):
        # 读 .env。铁律：禁止硬编码、禁止默认值写法。
        load_dotenv(os.path.join(BASE, ".env"))
        if "DEEPSEEK_API_KEY" not in os.environ:
            raise RuntimeError(
                "缺少 DEEPSEEK_API_KEY。请复制 .env.example 为 .env，填入你的 key（禁止写进任何代码文件）。"
            )
        key = os.environ["DEEPSEEK_API_KEY"].strip()
        if not key or key == "your_deepseek_api_key_here":
            raise RuntimeError("DEEPSEEK_API_KEY 还是占位符，请填真实 key。")

        from openai import OpenAI
        # timeout=60s：单次请求/流式空闲超时，避免网络挂起整场冻结（SDK 默认 600s 太久）。
        self.client = OpenAI(api_key=key, base_url=BASE_URL, timeout=60.0)
        materials = load_materials()
        # 表单填的 JD 优先；为空回退 jd.txt（换方向的口子仍有效）
        if not jd:
            jd = _read(JD_PATH)
        self.system_prompt = build_system_prompt(materials, jd, company)
        self.materials_titles = [t for t, _ in materials]

    def generate(self, history, on_chunk, extra="", temperature=0.6):
        """流式生成参考答案。

        history：带 [面试官]/[我] 标签、按时间排序的对话文本，最后一句应是面试官的问题。
        on_chunk(delta)：每收到一段就回调一次（M3 控制台打印，M5 接 Qt 信号）。
        extra：热键"换一版 / 换个角度"时追加的指令，M3 留空。
        temperature：默认 0.6 保持答案有变化；格式合规性测试传 0 求稳定。
        返回完整答案文本。
        """
        user_msg = (
            f"下面是最近的面试对话（按时间顺序）：\n\n{history}\n\n"
            f"请判断面试官最后说的那句话要不要回答，并严格按【输出格式】输出。{extra}"
        )
        stream = self.client.chat.completions.create(
            model=MODEL,
            messages=[
                {"role": "system", "content": self.system_prompt},
                {"role": "user", "content": user_msg},
            ],
            stream=True,
            temperature=temperature,
        )
        parts = []
        for chunk in stream:
            delta = ""
            if chunk.choices:
                choice = chunk.choices[0]
                if choice.delta and choice.delta.content:
                    delta = choice.delta.content
            if delta:
                parts.append(delta)
                on_chunk(delta)
        return "".join(parts)
